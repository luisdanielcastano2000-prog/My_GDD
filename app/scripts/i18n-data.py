here = os.path.dirname(os.path.abspath(__file__))
def emit(lang, idx, head):
    esc = lambda s: s.replace('\\', '\\\\').replace("'", "\\'")
    lines = [head, f"export const {lang.upper()}: Record<string, string> = {{"]
    for k, v in T.items():
        lines.append(f"  '{esc(k)}': '{esc(v[idx])}',")
    lines.append('};\n')
    open(os.path.join(here, f'../src/app/i18n/{lang}.ts'), 'w', encoding='utf8').write('\n'.join(lines))
